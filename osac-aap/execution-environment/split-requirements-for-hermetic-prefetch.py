#!/usr/bin/env python3
"""Split requirements.txt into requirements-rhtl.txt / requirements-pypi.txt.

Why this exists: Cachi2/Hermeto's pip prefetch resolves an --index-url
per requirements *file*, not per package (confirmed against Hermeto's
own source, hermeto/core/package_managers/python/pip/{requirements,
main}.py -- --extra-index-url is explicitly rejected, "we only support
one index"). osac-aap's hermetic build needs most pip packages fetched
as wheels from Red Hat's trusted-libraries PyPI proxy (required by the
shared Enterprise Contract policy-data's hermeto:pip:package:binary
except_when clause -- see requirements-rhtl.txt's own header), but
that proxy doesn't mirror 100% of public PyPI. requirements.txt itself
is generated by `uv pip compile` (see its own header) and must not be
hand-edited, so the packages missing from the trusted proxy are routed
to a second, PyPI-indexed file instead, computed by this script.

Regenerate after `uv pip compile` changes requirements.txt:

    python3 execution-environment/split-requirements-for-hermetic-prefetch.py

This only reads requirements.txt and (re)writes requirements-rhtl.txt
and requirements-pypi.txt; it does not touch requirements.txt itself.
The MISSING_FROM_TRUSTED_PROXY set below was determined by checking
each package name against
https://packages.redhat.com/trusted-libraries/python/<name>/ for a
200 vs 404 -- re-check it the same way if `uv pip compile` adds a new
dependency, in case the new package also isn't mirrored there.
"""
import re

# Confirmed 404 at https://packages.redhat.com/trusted-libraries/python/<name>/
# as of 2026-10-21. ansible-runner and python-esiclient are transitive-only
# (pulled in by python-esiclient, a git-sourced dependency); esisdk and
# python-esileapclient are direct osac-aap (pyproject.toml) dependencies.
MISSING_FROM_TRUSTED_PROXY = {
    "ansible-runner",
    "esisdk",
    "metalsmith",
    "python-esiclient",
    "python-esileapclient",
}


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def main() -> None:
    missing_norm = {normalize(n) for n in MISSING_FROM_TRUSTED_PROXY}
    rhtl_lines = []
    pypi_lines = []

    with open("execution-environment/requirements.txt") as f:
        for line in f:
            stripped = line.strip()
            if not stripped or stripped.startswith("#") or line[0] in (" ", "\t"):
                continue
            match = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)", stripped)
            if not match:
                raise ValueError(f"could not parse requirement name from line: {stripped!r}")
            name = normalize(match.group(1))
            (pypi_lines if name in missing_norm else rhtl_lines).append(stripped)

    unseen = missing_norm - {normalize(re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)", l).group(1)) for l in pypi_lines}
    if unseen:
        raise ValueError(f"MISSING_FROM_TRUSTED_PROXY entries not found in requirements.txt: {unseen}")

    rhtl_header = (
        "# Generated by split-requirements-for-hermetic-prefetch.py from\n"
        "# requirements.txt -- do not hand-edit, do not add new packages here\n"
        "# directly (add them to pyproject.toml and re-run `uv pip compile`,\n"
        "# then this script). Routed through Red Hat's trusted-libraries PyPI\n"
        "# proxy (prefetch-dependencies-oci-ta's pip-index-url param) so\n"
        "# Cachi2/Hermeto's wheel fetches carry a repository_url purl\n"
        "# qualifier matching the shared Enterprise Contract policy-data's\n"
        "# hermeto:pip:package:binary except_when clause -- confirmed via a\n"
        "# real release's EC failure otherwise (111 sbom_spdx.\n"
        "# disallowed_package_attributes violations, one per prefetched\n"
        "# wheel sourced from public PyPI instead).\n"
    )
    pypi_header = (
        "# Generated by split-requirements-for-hermetic-prefetch.py from\n"
        "# requirements.txt -- do not hand-edit. These packages 404 on Red\n"
        "# Hat's trusted-libraries PyPI proxy (confirmed live), so they're\n"
        "# routed to public PyPI instead via this file's own --index-url\n"
        "# line, which overrides prefetch-dependencies-oci-ta's pip-index-url\n"
        "# fallback for this file only (Hermeto resolves --index-url per\n"
        "# requirements file, not per package). All pure-Python, no C\n"
        "# extensions, so sdist-only (no \"binary\" allow-listing) is fine --\n"
        "# see the prefetch-input binary.packages allow-list in the pipeline\n"
        "# YAML, which intentionally excludes these so they don't trip\n"
        "# sbom_spdx.disallowed_package_attributes by fetching a wheel from\n"
        "# a non-trusted source.\n"
        "--index-url https://pypi.org/simple\n"
    )

    with open("execution-environment/requirements-rhtl.txt", "w") as f:
        f.write(rhtl_header)
        f.write("\n".join(rhtl_lines) + "\n")

    with open("execution-environment/requirements-pypi.txt", "w") as f:
        f.write(pypi_header)
        f.write("\n".join(pypi_lines) + "\n")

    print(f"wrote {len(rhtl_lines)} packages to requirements-rhtl.txt")
    print(f"wrote {len(pypi_lines)} packages to requirements-pypi.txt")


if __name__ == "__main__":
    main()
