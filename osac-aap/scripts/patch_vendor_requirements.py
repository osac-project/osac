#!/usr/bin/env python3
"""Apply OSAC-owned security overlays to generated collection artifacts.

The collection archives are generated by Ansible Galaxy and must not be edited
manually. This overlay is the maintained source for dependency constraints,
unused upstream test-dependency exclusions, targeted test/example corrections,
and sanitized documentation and credential examples.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


REQUIREMENT_FLOORS: dict[str, dict[str, str]] = {
    "ansible_collections/ansible/controller/requirements.txt": {"urllib3": "2.8.0"},
    "ansible_collections/kubernetes/core/requirements.txt": {"oauthlib": "4.0.1", "urllib3": "2.8.0"},
    "ansible_collections/kubernetes/core/test-requirements.txt": {"setuptools": "84.2.1"},
    "ansible_collections/openstack/cloud/requirements.txt": {
        "cryptography": "50.0.2",
        "setuptools": "84.2.1",
        "urllib3": "2.8.0",
    },
}

# This older floor was applied by a previous version of this overlay. Only
# explicit entries here may replace an existing OSAC-owned floor.
REQUIREMENT_FLOOR_UPDATES: dict[str, dict[str, str]] = {
    "ansible_collections/kubernetes/core/requirements.txt": {"oauthlib": "4.0.0"}
}
REQUIREMENT_FLOOR_COMMENT = "# OSAC security floors; maintained in scripts/patch_vendor_requirements.py."

REMOVED_TEST_REQUIREMENTS: dict[str, dict[str, str]] = {
    "ansible_collections/ansible/utils/test-requirements.txt": {"ansible-navigator": "ansible-navigator"},
    "ansible_collections/amazon/aws/test-requirements.txt": {"aiobotocore": "aiobotocore[botocore]"},
}

AMAZON_INVENTORY_ERROR_TEST = (
    "ansible_collections/amazon/aws/tests/unit/plugins/plugin_utils/inventory/test_inventory_error_handler.py"
)
AMAZON_INVENTORY_URL_ASSERTION = '        assert "ec2.us-east-1.amazonaws.com" in str(raised.exception)'
AMAZON_INVENTORY_URL_ASSERTION_FIXED = (
    '        assert raised.exception.kwargs["endpoint_url"] == "https://ec2.us-east-1.amazonaws.com"'
)
AMAZON_EC2_TAG_SOURCE = "ec2_tags" + "." + "Application"
AMAZON_EC2_TAG_PREVIOUS = "ec2_tags" + "." + "Environment"
AMAZON_EC2_TAG_TARGET = "ec2_tags[" + "'Environment'" + "]"
AMAZON_EC2_TAG_EXAMPLE_REWRITES = {
    "ansible_collections/amazon/aws/docs/docsite/rst/aws_ec2_guide.rst": (
        "    # This creates a host group for each value of the Application tag.\n    - key: " + AMAZON_EC2_TAG_SOURCE,
        "    # This creates a host group for each value of the Environment tag.\n    - key: " + AMAZON_EC2_TAG_TARGET,
    ),
    "ansible_collections/amazon/aws/plugins/inventory/aws_ec2.py": (
        "  # Create a group for each value of the Application tag\n  - key: " + AMAZON_EC2_TAG_SOURCE,
        "  # Create a group for each value of the Environment tag\n  - key: " + AMAZON_EC2_TAG_TARGET,
    ),
}

FLASHBLADE_MODULE_DIR = "ansible_collections/everpure/flashblade/plugins/modules"
# Keep this exact for the pinned collection archive; an upstream update needs
# review before new example credentials are sanitized.
FLASHBLADE_API_TOKEN_FIELDS = 275
FLASHBLADE_EXAMPLE_TOKEN = "replace-me"
FLASHBLADE_EXAMPLES_BLOCK = re.compile(r"(?m)^\s*EXAMPLES\s*=\s*r?(?P<delimiter>\"\"\"|''')")
FLASHBLADE_API_TOKEN_LINE = re.compile(
    r"""(?m)^([ \t]*api_token:[ \t]*)(?:"[^"\n]*"|'[^'\n]*'|[^\s#]+)([ \t]*(?:#.*)?)$"""
)

CONTROLLER_SUBSCRIPTIONS_EXAMPLES = "ansible_collections/ansible/controller/plugins/modules/subscriptions.py"
CONTROLLER_EXAMPLE_CREDENTIAL = "replace-me"
KUBECONFIG_EXAMPLE_FILES = (
    "ansible_collections/kubernetes/core/plugins/modules/kubeconfig.py",
    "ansible_collections/kubernetes/core/docs/kubernetes.core.kubeconfig_module.rst",
)
KUBECONFIG_EXAMPLE_TOKEN = "replace-with-service-account-token"
KUBECONFIG_TOKEN_LINE = re.compile(r"""(?m)^(\s*token:\s*)(["']?)([^\s"'#]+)(["']?)(\s*(?:#.*)?)$""")


def _package_name(line: str) -> str | None:
    requirement = line.split("#", maxsplit=1)[0].strip()
    match = re.match(r"^([A-Za-z0-9_.-]+)", requirement)
    if match is None:
        return None
    return re.sub(r"[-_.]+", "-", match.group(1)).lower()


def _normalized_requirement(line: str) -> str:
    return re.sub(r"\s+", "", line.split("#", maxsplit=1)[0]).lower()


def apply_overrides(vendor_dir: Path) -> int:
    """Add dependency floors to generated collection requirement files.

    Upgrade only explicitly listed earlier OSAC floors. Fail if an upstream
    collection declares another constraint; it needs review instead of a
    silent merge. Return the number of manifests changed.
    """
    changed = 0
    for relative_path, floors in REQUIREMENT_FLOORS.items():
        path = vendor_dir / relative_path
        if not path.is_file():
            raise FileNotFoundError(f"expected vendored requirements file: {path}")

        lines = path.read_text(encoding="utf-8").splitlines()
        existing: dict[str, list[str]] = {}
        for line in lines:
            package = _package_name(line)
            if package is not None:
                existing.setdefault(package, []).append(line)

        additions: list[str] = []
        replaced = False
        for package, version in floors.items():
            expected = f"{package}>={version}"
            prior = existing.get(package, [])
            if prior:
                if len(prior) == 1 and _normalized_requirement(prior[0]) == expected:
                    continue
                old_version = REQUIREMENT_FLOOR_UPDATES.get(relative_path, {}).get(package)
                old_floor = f"{package}>={old_version}" if old_version else None
                if len(prior) == 1 and old_floor is not None and _normalized_requirement(prior[0]) == old_floor:
                    index = lines.index(prior[0])
                    if index == 0 or lines[index - 1].strip() != REQUIREMENT_FLOOR_COMMENT:
                        raise ValueError(
                            f"{path} has an unmarked previous floor for {package}; review the collection update"
                        )
                    lines[index] = expected
                    existing[package] = [expected]
                    replaced = True
                    continue
                raise ValueError(
                    f"{path} already declares {package}: {prior!r}; review the collection update and security floor"
                )
            additions.append(expected)

        if not additions and not replaced:
            continue

        if additions:
            if lines and lines[-1].strip():
                lines.append("")
            lines.append(REQUIREMENT_FLOOR_COMMENT)
            lines.extend(additions)
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        changed += 1

    return changed


def fix_amazon_inventory_error_assertion(vendor_dir: Path) -> bool:
    """Use the structured endpoint value in an upstream test assertion.

    The upstream substring assertion triggers CodeQL's incomplete URL
    sanitization query, although it only checks a test fixture's exception.
    """
    path = vendor_dir / AMAZON_INVENTORY_ERROR_TEST
    if not path.is_file():
        raise FileNotFoundError(f"expected vendored test file: {path}")

    source = path.read_text(encoding="utf-8")
    if AMAZON_INVENTORY_URL_ASSERTION_FIXED in source:
        return False
    if source.count(AMAZON_INVENTORY_URL_ASSERTION) != 1:
        raise ValueError(f"{path} no longer has the expected endpoint assertion; review the upstream test")

    path.write_text(
        source.replace(AMAZON_INVENTORY_URL_ASSERTION, AMAZON_INVENTORY_URL_ASSERTION_FIXED, 1), encoding="utf-8"
    )
    return True


def fix_amazon_ec2_tag_examples(vendor_dir: Path) -> int:
    """Replace a public AWS tag-path example that triggers secret scanning."""
    changed = 0
    for relative_path, (old, new) in AMAZON_EC2_TAG_EXAMPLE_REWRITES.items():
        path = vendor_dir / relative_path
        if not path.is_file():
            raise FileNotFoundError(f"expected vendored AWS example: {path}")

        source = path.read_text(encoding="utf-8")
        if new in source and old not in source:
            continue
        previous = old.replace("Application tag", "Environment tag").replace(
            AMAZON_EC2_TAG_SOURCE, AMAZON_EC2_TAG_PREVIOUS
        )
        if source.count(old) == 1:
            prior = old
        elif source.count(previous) == 1:
            prior = previous
        else:
            raise ValueError(f"{path} no longer has the expected Application tag example; review the upstream example")

        path.write_text(source.replace(prior, new, 1), encoding="utf-8")
        changed += 1

    return changed


def sanitize_flashblade_example_tokens(vendor_dir: Path) -> int:
    """Replace upstream fake API tokens in Everpure module EXAMPLES blocks.

    These sample tokens are not credentials for OSAC systems. Sanitizing them
    in the generated vendor tree keeps secret scanners useful without adding
    an allowlist for third-party example values.
    """
    module_dir = vendor_dir / FLASHBLADE_MODULE_DIR
    if not module_dir.is_dir():
        raise FileNotFoundError(f"expected vendored FlashBlade modules: {module_dir}")

    updates: dict[Path, str] = {}
    field_count = 0
    replacement_count = 0
    placeholder = re.compile(r"""^[ \t]*api_token:\s*["']?replace-me["']?\s*(?:#.*)?$""")
    for path in sorted(module_dir.glob("*.py")):
        original = path.read_text(encoding="utf-8")
        source = original
        examples = list(FLASHBLADE_EXAMPLES_BLOCK.finditer(source))
        for example in reversed(examples):
            delimiter = example.group("delimiter")
            start = example.end()
            end = source.find(delimiter, start)
            if end < 0:
                raise ValueError(f"{path} has an unterminated EXAMPLES block")

            block = source[start:end]

            def replace_token(match: re.Match[str]) -> str:
                nonlocal replacement_count
                line = match.group(0)
                if placeholder.fullmatch(line):
                    return line
                replacement_count += 1
                return f'{match.group(1)}"{FLASHBLADE_EXAMPLE_TOKEN}"{match.group(2)}'

            sanitized, matches = FLASHBLADE_API_TOKEN_LINE.subn(replace_token, block)
            field_count += matches
            if sanitized != block:
                source = source[:start] + sanitized + source[end:]

        if source != original:
            updates[path] = source

    if field_count != FLASHBLADE_API_TOKEN_FIELDS:
        raise ValueError(
            "expected "
            f"{FLASHBLADE_API_TOKEN_FIELDS} FlashBlade API token examples, "
            f"found {field_count}; review the upstream collection update"
        )

    for path, source in updates.items():
        path.write_text(source, encoding="utf-8")

    return replacement_count


def remove_unused_test_requirements(vendor_dir: Path) -> int:
    """Remove upstream test-only tools OSAC does not use.

    Fail if upstream changes a removed requirement so the exclusion can be
    reviewed rather than silently broadening it. Return manifests changed.
    """
    changed = 0
    for relative_path, removals in REMOVED_TEST_REQUIREMENTS.items():
        path = vendor_dir / relative_path
        if not path.is_file():
            raise FileNotFoundError(f"expected vendored requirements file: {path}")

        lines = path.read_text(encoding="utf-8").splitlines()
        remove_indexes: set[int] = set()
        for package, expected in removals.items():
            matches = [(index, line) for index, line in enumerate(lines) if _package_name(line) == package]
            if not matches:
                continue
            if len(matches) != 1 or _normalized_requirement(matches[0][1]) != expected:
                raise ValueError(
                    f"{path} declares {package}: {[line for _, line in matches]!r}; "
                    "review the upstream test dependency before removing it"
                )

            index, _ = matches[0]
            remove_indexes.add(index)

        if remove_indexes:
            path.write_text(
                "\n".join(line for index, line in enumerate(lines) if index not in remove_indexes) + "\n",
                encoding="utf-8",
            )
            changed += 1

    return changed


def sanitize_controller_example_credentials(vendor_dir: Path) -> bool:
    """Replace upstream client-secret literals in the module's EXAMPLES block.

    This collection ships random-looking credentials in public documentation
    examples. Keep the patch scoped to that block and fail if its shape changes.
    """
    path = vendor_dir / CONTROLLER_SUBSCRIPTIONS_EXAMPLES
    if not path.is_file():
        raise FileNotFoundError(f"expected vendored example module: {path}")

    source = path.read_text(encoding="utf-8")
    marker = "EXAMPLES = '''"
    start = source.find(marker)
    if start < 0:
        raise ValueError(f"{path} no longer has the expected EXAMPLES block")
    block_start = start + len(marker)
    block_end = source.find("'''", block_start)
    if block_end < 0:
        raise ValueError(f"{path} has an unterminated EXAMPLES block")

    examples = source[block_start:block_end]
    pattern = re.compile(r"""(?m)^(\s*client_secret:\s*)(?:"[^"\n]*"|'[^'\n]*'|[^\s#]+)(\s*(?:#.*)?)$""")
    sanitized, replacements = pattern.subn(rf'\1"{CONTROLLER_EXAMPLE_CREDENTIAL}"\2', examples)
    if replacements != 2:
        raise ValueError(f"{path} expected two client_secret values in EXAMPLES, found {replacements}")
    if sanitized == examples:
        return False

    path.write_text(source[:block_start] + sanitized + source[block_end:], encoding="utf-8")
    return True


def sanitize_kubeconfig_example_tokens(vendor_dir: Path) -> int:
    """Replace JWT-shaped tokens in the vendored kubeconfig docs/examples."""
    changed = 0
    for relative_path in KUBECONFIG_EXAMPLE_FILES:
        path = vendor_dir / relative_path
        if not path.is_file():
            raise FileNotFoundError(f"expected vendored kubeconfig example: {path}")

        source = path.read_text(encoding="utf-8")
        replacements = 0

        def replace_example_token(match: re.Match[str]) -> str:
            nonlocal replacements
            token = match.group(3)
            if len(token) < 24 or token.count(".") < 2:
                return match.group(0)
            replacements += 1
            return f'{match.group(1)}"{KUBECONFIG_EXAMPLE_TOKEN}"{match.group(5)}'

        sanitized = KUBECONFIG_TOKEN_LINE.sub(replace_example_token, source)
        if replacements == 0 and source.count(KUBECONFIG_EXAMPLE_TOKEN) == 1:
            continue
        if replacements != 1:
            raise ValueError(f"{path} expected one JWT-shaped token example, found {replacements}")
        path.write_text(sanitized, encoding="utf-8")
        changed += 1
    return changed


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--vendor-dir", type=Path, default=Path(__file__).resolve().parents[1] / "vendor")
    args = parser.parse_args()
    changed = apply_overrides(args.vendor_dir)
    removed = remove_unused_test_requirements(args.vendor_dir)
    corrected_test = fix_amazon_inventory_error_assertion(args.vendor_dir)
    corrected_tags = fix_amazon_ec2_tag_examples(args.vendor_dir)
    sanitized_flashblade_tokens = sanitize_flashblade_example_tokens(args.vendor_dir)
    sanitized_example = sanitize_controller_example_credentials(args.vendor_dir)
    sanitized_tokens = sanitize_kubeconfig_example_tokens(args.vendor_dir)
    print(
        f"Applied OSAC dependency floors to {changed} vendored manifests; "
        f"removed unused upstream test dependencies from {removed} manifests; "
        f"corrected upstream test assertion: {int(corrected_test)}; "
        f"corrected AWS tag examples: {corrected_tags}; "
        f"sanitized FlashBlade example tokens: {sanitized_flashblade_tokens}; "
        f"sanitized upstream credential examples: "
        f"{int(sanitized_example) + sanitized_tokens}."
    )


if __name__ == "__main__":
    main()
