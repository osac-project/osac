def _replace_exactly_once(source: str, old: str, new: str, path: Path, description: str) -> tuple[str, bool]:
    """Replace one pinned upstream block, accepting an already-applied patch."""
    patched_count = source.count(new)
    if patched_count:
        if patched_count != 1 or old in source.replace(new, "", 1):
            raise ValueError(f"{path} contains ambiguous old and patched {description}; review the vendor update")
        return source, False
    if source.count(old) != 1:
        raise ValueError(f"{path} no longer has the expected {description}; review the upstream update")
    return source.replace(old, new, 1), True


def _apply_exact_rewrites(
    vendor_dir: Path,
    relative_path: str,
    rewrites: tuple[tuple[str, str, str], ...],
) -> int:
    """Apply pinned, idempotent text rewrites to one vendored source file."""
    path = vendor_dir / relative_path
    if not path.is_file():
        raise FileNotFoundError(f"expected vendored source file: {path}")

    original = path.read_text(encoding="utf-8")
    source = original
    changed = 0
    for old, new, description in rewrites:
        source, replaced = _replace_exactly_once(source, old, new, path, description)
        changed += int(replaced)

    if source != original:
        path.write_text(source, encoding="utf-8")
    return changed


