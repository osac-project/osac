var (
	ErrAccountNotFound                 = errors.New("billing account not found")
	ErrTenantBillingAssignmentNotFound = errors.New("tenant has no active billing account assignment")
)

// AssignedAccount contains the provider reference needed for tenant-specific
// pricing lookups. The provider-native reference is never returned to callers.
type AssignedAccount struct {
	ProviderKey              string
	ProviderAccountReference string
	CurrencyCode             string
	ConnectionState          string
}

// AccountStore persists provider-global account references without assigning
// them to an OSAC tenant. Account IDs are generated by OSAC and remain stable
// when an account is rediscovered.
type AccountStore struct{}

func NewAccountStore() *AccountStore {
	return &AccountStore{}
}

// SyncAccounts inserts or refreshes discovered provider accounts, preserves
// their first known currency, and returns them with stable OSAC identifiers.
func (s *AccountStore) SyncAccounts(
	ctx context.Context,
	providerKey string,
	accounts []Account,
	observedAt time.Time,
) (result []*privatev1.BillingAccount, err error) {
	tx, err := database.TxFromContext(ctx)
	if err != nil {
		return nil, err
	}
	defer tx.ReportError(&err)
	if providerKey == "" {
		return nil, errors.New("billing provider key is required")
	}
	if observedAt.IsZero() {
		return nil, errors.New("billing account observation time is required")
	}
	result = make([]*privatev1.BillingAccount, 0, len(accounts))
	for _, account := range accounts {
		if account.Reference == "" || account.DisplayName == "" {
			return nil, errors.New("provider account ID and display name are required")
		}
		account.Currency = strings.ToUpper(strings.TrimSpace(account.Currency))
		if account.Currency != "" && !validCurrencyCode(account.Currency) {
			return nil, fmt.Errorf("provider account currency %q is not a valid ISO-4217 code", account.Currency)
		}
		id := uuid.New()
		var storedID, storedCurrency string
		if err = tx.QueryRow(ctx, `
			insert into billing_accounts (
				id, provider_key, provider_account_reference, display_name, base_currency, state, status_observed_at
			) values ($1, $2, $3, $4, $5, $6, $7)
			on conflict (provider_key, provider_account_reference) do update set
				display_name = excluded.display_name,
				base_currency = case when billing_accounts.base_currency = '' then excluded.base_currency
					else billing_accounts.base_currency end,
				state = excluded.state,
				status_observed_at = excluded.status_observed_at
			returning id, base_currency
		`, id, providerKey, account.Reference, account.DisplayName, account.Currency,
			accountStateName(account.State), observedAt).Scan(&storedID, &storedCurrency); err != nil {
			return nil, fmt.Errorf("failed to persist discovered billing account: %w", err)
		}
		account.Currency = storedCurrency
		result = append(result, makeBillingAccount(storedID, providerKey, account, observedAt))
	}
	return result, nil
}

// GetAccount retrieves an account by its OSAC-generated identifier.
func (s *AccountStore) GetAccount(ctx context.Context, id string) (result *privatev1.BillingAccount, err error) {
	tx, err := database.TxFromContext(ctx)
	if err != nil {
		return nil, err
	}
	defer tx.ReportError(&err)
	var (
		providerKey string
		reference   string
		name        string
		currency    string
		state       string
		observedAt  time.Time
	)
	err = tx.QueryRow(ctx, `
		select provider_key, provider_account_reference, display_name, base_currency, state, status_observed_at
		from billing_accounts where id = $1
	`, id).Scan(&providerKey, &reference, &name, &currency, &state, &observedAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, ErrAccountNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("failed to retrieve billing account: %w", err)
	}
	return privatev1.BillingAccount_builder{
		Id:                       id,
		ProviderKey:              providerKey,
		ProviderAccountReference: reference,
		DisplayName:              name,
		BaseCurrency:             currency,
		State:                    accountStateProto(state),
		StatusObservedAt:         timestamppb.New(observedAt),
	}.Build(), nil
}

// GetAssignedAccount returns the connected billing account for a tenant's
// active assignment. The provider-native account reference stays server-side.
func (s *AccountStore) GetAssignedAccount(ctx context.Context, tenantID string) (result AssignedAccount, err error) {
	if tenantID == "" {
		return AssignedAccount{}, errors.New("tenant ID is required")
	}
	tx, err := database.TxFromContext(ctx)
	if err != nil {
		return AssignedAccount{}, err
	}
	defer tx.ReportError(&err)
	err = tx.QueryRow(ctx, `
		select b.provider_key, b.provider_account_reference, b.base_currency,
			a.data #>> '{status,connection_state}'
		from tenant_billing_assignments a
		join billing_accounts b on b.id = a.billing_account_id
		where a.tenant = $1 and a.deletion_timestamp = 'epoch'
			and coalesce(a.effective_to, '') = ''
	`, tenantID).Scan(
		&result.ProviderKey,
		&result.ProviderAccountReference,
		&result.CurrencyCode,
		&result.ConnectionState,
	)
	if errors.Is(err, pgx.ErrNoRows) {
		return AssignedAccount{}, ErrTenantBillingAssignmentNotFound
	}
	if err != nil {
		return AssignedAccount{}, fmt.Errorf("failed to retrieve tenant billing account: %w", err)
	}
	return result, nil
}

// CloseTenantAssignment ends the active link when its OSAC tenant is deleted.
// The provider account and assignment history remain intact so delayed usage
// keeps its existing provider-side attribution until an administrator reassigns it.
func (s *AccountStore) CloseTenantAssignment(ctx context.Context, tenantID string) (err error) {
	if tenantID == "" {
		return errors.New("tenant ID is required")
	}
	tx, err := database.TxFromContext(ctx)
	if err != nil {
		return err
	}
	defer tx.ReportError(&err)
	_, err = tx.Exec(ctx, `
		update tenant_billing_assignments
		set data = jsonb_set(data, '{status,effective_to}', to_jsonb($2::text), true),
			version = version + 1
		where tenant = $1 and deletion_timestamp = 'epoch'
			and coalesce(effective_to, '') = ''
	`, tenantID, time.Now().UTC().Format(time.RFC3339Nano))
	if err != nil {
		return fmt.Errorf("failed to close tenant billing assignment: %w", err)
	}
	return nil
}

// ListAccounts retrieves provider accounts using OSAC pagination.
func (s *AccountStore) ListAccounts(
	ctx context.Context,
	providerKey string,
	offset int32,
	limit int32,
) (items []*privatev1.BillingAccount, total int32, err error) {
	tx, err := database.TxFromContext(ctx)
	if err != nil {
		return nil, 0, err
	}
	defer tx.ReportError(&err)
	if limit <= 0 {
		limit = 100
	}
	if offset < 0 {
		return nil, 0, errors.New("billing account offset must not be negative")
	}
	err = tx.QueryRow(ctx, `select count(*) from billing_accounts where provider_key = $1`, providerKey).Scan(&total)
	if err != nil {
		return nil, 0, fmt.Errorf("failed to count billing accounts: %w", err)
	}
	rows, err := tx.Query(ctx, `
		select id, provider_account_reference, display_name, base_currency, state, status_observed_at
		from billing_accounts where provider_key = $1
		order by display_name, id limit $2 offset $3
	`, providerKey, limit, offset)
	if err != nil {
		return nil, 0, fmt.Errorf("failed to list billing accounts: %w", err)
	}
	defer rows.Close()
	items = make([]*privatev1.BillingAccount, 0)
	for rows.Next() {
		var (
			id         string
			reference  string
			name       string
			currency   string
			state      string
			observedAt time.Time
		)
		if err = rows.Scan(&id, &reference, &name, &currency, &state, &observedAt); err != nil {
			return nil, 0, fmt.Errorf("failed to read billing account: %w", err)
		}
		items = append(items, privatev1.BillingAccount_builder{
			Id:                       id,
			ProviderKey:              providerKey,
			ProviderAccountReference: reference,
			DisplayName:              name,
			BaseCurrency:             currency,
			State:                    accountStateProto(state),
			StatusObservedAt:         timestamppb.New(observedAt),
		}.Build())
	}
	if err = rows.Err(); err != nil {
		return nil, 0, fmt.Errorf("failed to iterate billing accounts: %w", err)
	}
	return items, total, nil
}

func makeBillingAccount(id, providerKey string, account Account, observedAt time.Time) *privatev1.BillingAccount {
	return privatev1.BillingAccount_builder{
		Id:                       id,
		ProviderKey:              providerKey,
		ProviderAccountReference: account.Reference,
		DisplayName:              account.DisplayName,
		BaseCurrency:             account.Currency,
		State:                    accountStateEnum(account.State),
		StatusObservedAt:         timestamppb.New(observedAt),
	}.Build()
}

func accountStateName(state AccountState) string {
	switch state {
	case AccountStateActive:
		return "ACTIVE"
	case AccountStateInactive:
		return "INACTIVE"
	default:
		return "UNKNOWN"
	}
}

func accountStateProto(state string) privatev1.BillingAccountState {
	switch state {
	case "ACTIVE":
		return privatev1.BillingAccountState_BILLING_ACCOUNT_STATE_ACTIVE
	case "INACTIVE":
		return privatev1.BillingAccountState_BILLING_ACCOUNT_STATE_INACTIVE
	default:
		return privatev1.BillingAccountState_BILLING_ACCOUNT_STATE_UNKNOWN
	}
}

func accountStateEnum(state AccountState) privatev1.BillingAccountState {
	return accountStateProto(accountStateName(state))
}
