def _patch_vast_result_exits(
    source: str,
    path: Path,
    expected_count: int,
    add_helper: bool,
) -> str:
    old_call = "self.module.exit_json("
    new_call = "self._exit_json_with_redaction("
    old_count = source.count(old_call)
    new_count = source.count(new_call)
    helper_marker = "    def _exit_json_with_redaction(self, **kwargs: Any) -> None:\n"

    if add_helper:
        if helper_marker in source:
            if new_count != expected_count or old_count != 1:
                raise ValueError(f"{path} has incomplete output redaction; review the vendor update")
            return source
        if old_count != expected_count or new_count:
            raise ValueError(
                f"{path} no longer has {expected_count} expected module outputs; review the vendor update"
            )
        source = source.replace(old_call, new_call)
        anchor = "    def run(self) -> None:\n"
        if source.count(anchor) != 1:
            raise ValueError(f"{path} no longer has the expected run method; review the vendor update")
        source = source.replace(anchor, VAST_OUTPUT_REDACTION_METHOD + anchor, 1)
        return source

    if old_count == 0 and new_count == expected_count:
        return source
    if old_count != expected_count or new_count:
        raise ValueError(
            f"{path} no longer has {expected_count} expected module outputs; review the vendor update"
        )
    return source.replace(old_call, new_call)


